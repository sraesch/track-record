#!/usr/bin/env bash
# Builds the images and deploys the whole stack (database, server, web UI) to
# the local Docker Desktop Kubernetes cluster. Run it again after changes:
# only images whose content changed are rolled out.
#
#   deploy/local/up.sh             build, push and deploy
#   deploy/local/forward.sh        then open the UI and API on localhost
#   deploy/local/down.sh           remove everything (including the data)
#
# Docker Desktop's kind-based Kubernetes does not see images built with
# `docker build`. They go to a registry inside the cluster (registry.yaml,
# NodePort 30500). The Docker daemon reaches it through a small relay
# container on localhost:30500 (Docker allows plain HTTP for localhost), and
# the node pulls from its own localhost:30500.
#
# Needs Docker Desktop with Kubernetes enabled, and kubectl.
# KUBE_CONTEXT overrides the context (default docker-desktop).
set -euo pipefail

root=$(cd "$(dirname "$0")/../.." && pwd)
here="$root/deploy/local"
context=${KUBE_CONTEXT:-docker-desktop}
registry=localhost:30500
relay=track-record-registry-relay

k() { kubectl --context "$context" "$@"; }
log() { printf '\n==> %s\n' "$*"; }

k get nodes >/dev/null || { echo "Kubernetes context $context is not reachable" >&2; exit 1; }

log "Building images"
docker build --tag track-record-db:local "$root/db"
docker build --file "$root/backend/Dockerfile" --tag track-record-server:local "$root"
docker build --tag track-record-frontend:local "$root/frontend"

log "Starting the in-cluster registry"
k apply -f "$here/registry.yaml"
k -n track-record-registry rollout status deploy/registry --timeout=180s

node_ip=$(k get nodes -o jsonpath='{.items[0].status.addresses[?(@.type=="InternalIP")].address}')
docker rm --force "$relay" >/dev/null 2>&1 || true
docker run --detach --rm --name "$relay" --network host alpine/socat:1.8.0.3 \
    "TCP-LISTEN:30500,fork,reuseaddr,bind=127.0.0.1" "TCP:$node_ip:30500" >/dev/null
trap 'docker rm --force "$relay" >/dev/null 2>&1 || true' EXIT

# Wait until the registry answers through the relay, as the daemon sees it.
for _ in $(seq 1 30); do
    if docker run --rm --network host curlimages/curl:8.11.1 \
        --silent --fail --max-time 3 --output /dev/null "http://$registry/v2/"; then
        break
    fi
    sleep 1
done

log "Pushing images"
overlay="$here/.generated"
mkdir -p "$overlay"
{
    echo "# Generated by up.sh: the local stack with the images just pushed."
    echo "apiVersion: kustomize.config.k8s.io/v1beta1"
    echo "kind: Kustomization"
    echo "resources:"
    echo "  - ../base"
    echo "images:"
} >"$overlay/kustomization.yaml"
for name in track-record-db track-record-server track-record-frontend; do
    # Tag by content (layers and config, not the image ID, which carries the
    # build time), so pods roll only when an image really changed.
    tag=$(docker image inspect --format '{{json .RootFS.Layers}} {{json .Config}}' "$name:local" \
        | shasum -a 256 | cut -c 1-12)
    docker tag "$name:local" "$registry/$name:$tag"
    for attempt in 1 2 3; do
        docker push --quiet "$registry/$name:$tag" && break
        [ "$attempt" -lt 3 ] || { echo "push of $name failed" >&2; exit 1; }
        sleep 3
    done
    printf '  - name: %s\n    newTag: "%s"\n' "$registry/$name" "$tag" >>"$overlay/kustomization.yaml"
done

log "Deploying"
k apply -k "$overlay"
k -n track-record rollout status statefulset/db --timeout=300s
k -n track-record rollout status deploy/server --timeout=300s
k -n track-record rollout status deploy/frontend --timeout=180s
k -n track-record get pods

log "Done. Open the UI with: deploy/local/forward.sh"
